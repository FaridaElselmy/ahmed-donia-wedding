import { S3Client, GetObjectCommand } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

export function storage({ forCors = false } = {}) {
  const env = process.env;
  const accessKeyId = forCors ? env.B2_CORS_KEY_ID : env.B2_APPLICATION_KEY_ID;
  const secretAccessKey = forCors ? env.B2_CORS_KEY : env.B2_APPLICATION_KEY;
  const bucket = env.B2_BUCKET_NAME;
  const region = env.B2_REGION;
  const endpoint = (env.B2_ENDPOINT || '').replace(/\/+$/, '');
  if (![accessKeyId, secretAccessKey, bucket, region, endpoint].every(Boolean))
    throw new Error(`Missing Backblaze settings for ${forCors ? 'CORS' : 'storage'}.`);
  if (!/^https:\/\/s3\.[a-z0-9-]+\.backblazeb2\.com$/i.test(endpoint))
    throw new Error('B2_ENDPOINT must look like https://s3.us-west-004.backblazeb2.com');
  if (!endpoint.includes(`s3.${region}.`))
    throw new Error('B2_REGION must match the B2_ENDPOINT region.');
  const client = new S3Client({
    region,
    endpoint,
    forcePathStyle: true,
    credentials: { accessKeyId, secretAccessKey },
    maxAttempts: 3,
    // B2 does not need SDK-added CRC32 headers on presigned browser PUTs.
    requestChecksumCalculation: 'WHEN_REQUIRED',
    responseChecksumValidation: 'WHEN_REQUIRED'
  });
  return { client, bucket };
}

export async function viewUrl(client, bucket, key) {
  if (!key) return null;
  return getSignedUrl(client, new GetObjectCommand({ Bucket: bucket, Key: key }), {
    expiresIn: 60 * 60 * 2 // refreshable URLs for 2 hours
  });
}

// Keys generated by our API, not arbitrary paths or URLs.
export const isWeddingKey = value =>
  typeof value === 'string' &&
  /^wedding\/[0-9]{13}-[a-f0-9-]{36}\.(?:jpg|png|webp|mp4|mov|webm|m4v|3gp)$/.test(value);
